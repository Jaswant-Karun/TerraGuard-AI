from datetime import UTC, datetime
from typing import Any, Literal

from pydantic import BaseModel, Field, model_validator


class ChatMessage(BaseModel):
    role: Literal["user", "assistant", "system"]
    content: str
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat()
    )


class AgentActivityStep(BaseModel):
    agent: str
    action: str  # e.g. "QUERYING_TELEMETRY", "EVALUATING_ML_MODEL", "SYNTHESIZING_PLAN"
    description: str
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat()
    )


class ActionPlanItem(BaseModel):
    priority: Literal["CRITICAL", "HIGH", "MEDIUM", "LOW"]
    department: str  # e.g. "MUNICIPAL_DRAINAGE_CORPS", "TRAFFIC_MANAGEMENT", "CIVIL_DEFENSE"
    action: str
    target_location: str
    estimated_timeframe: str


class AgentChatRequest(BaseModel):
    message: str = Field(default="Provide an operational risk assessment for this area.", max_length=2000)
    lat: float = Field(default=12.9716, ge=-90.0, le=90.0)
    lng: float = Field(default=77.5946, ge=-180.0, le=180.0)
    location_name: str | None = Field(default="Bengaluru Central")
    history: list[ChatMessage] = Field(default_factory=list)
    agent_override: str | None = Field(
        default=None,
        description="Optional manual agent selector (e.g. 'FLOOD_RISK_AGENT')",
    )

    @model_validator(mode="before")
    @classmethod
    def resolve_fields_and_aliases(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Resolve message from common synonyms: prompt, query, text, question, input, content
            resolved_msg = (
                data.get("message")
                or data.get("prompt")
                or data.get("query")
                or data.get("text")
                or data.get("question")
                or data.get("input")
                or data.get("content")
            )
            if resolved_msg:
                data["message"] = str(resolved_msg).strip()
            elif "message" not in data or not data["message"]:
                data["message"] = "Provide an operational risk assessment and emergency response recommendation for this area."

            # Cast coordinates if passed as string
            if "lat" in data and data["lat"] is not None:
                try:
                    data["lat"] = float(data["lat"])
                except (ValueError, TypeError):
                    data["lat"] = 12.9716
            if "lng" in data and data["lng"] is not None:
                try:
                    data["lng"] = float(data["lng"])
                except (ValueError, TypeError):
                    data["lng"] = 77.5946

        return data


class AgentChatResponse(BaseModel):
    conversation_id: str
    reply: str
    identified_domain: str
    agent_name: str
    agent_activity: list[AgentActivityStep]
    factual_data_sources: list[str]
    structured_action_plan: list[ActionPlanItem] | None = None
    risk_summary: dict[str, Any] | None = None
    advisory_notice: str = (
        "⚠️ ADVISORY NOTICE: All recommendations generated by TerraGuard AI are strictly advisory "
        "decision-support insights. Official directives issued by municipal disaster management "
        "authorities, emergency services, and civil protection take absolute precedence."
    )


class AgentInfo(BaseModel):
    id: str
    name: str
    domain: str
    description: str
    capabilities: list[str]

